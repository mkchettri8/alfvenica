/* Package the accepted CommonJS Wind modules for the local browser workbench. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const Runner = require('./research-runner.js');
const Identity = require('./research-source-identity.js');
const root = __dirname;
const modules = [
  './interval-import.js', './model-compatibility.js', './interval-analysis.js',
  './research-sensitivity.js', './research-uncertainty.js', './research-bundle.js',
];
function build() {
  const formulaIdentities = Object.fromEntries(global.PlasmaFormulaRegistry.formulas.map(formula =>
    [formula.id, Runner.formulaIdentity(formula)]));
  const bridge = `
const factories = Object.create(null), cache = Object.create(null);
const formulaIdentities = ${JSON.stringify(formulaIdentities)};
const calculatorSourceIdentity = ${JSON.stringify(Runner.sourceIdentity())};
const buildIdentity = ${JSON.stringify(Identity.sourceIdentity())};
factories['./research-runner.js'] = function(require, module) {
  const Registry = root.PlasmaFormulaRegistry, Units = root.PlasmaUnitRegistry;
  const Exporter = root.AlfvenicaReproducibleExport;
  module.exports = Object.freeze({
    formulaIdentity(formula) { return formulaIdentities[formula.id]; },
    sourceIdentity() { return calculatorSourceIdentity; },
    run(state) {
      const formula = Registry.formulas.find(item => item.id === state?.formula_id);
      if (!formula) return { ok: false, error: { code: 'UNKNOWN_FORMULA', message: 'Unknown formula ID' } };
      const inputs = state.canonical_inputs;
      if (!inputs || Object.keys(inputs).length !== formula.inputs.length ||
          formula.inputs.some(input => !Number.isFinite(inputs[input.key]) ||
            state.input_units?.[input.key] !== Units.canonicalQuantities[input.quantity].unit)) {
        return { ok: false, error: { code: 'INVALID_INPUT', message: 'Canonical inputs or units differ' } };
      }
      try {
        const record = Exporter.createRecord({ formula, canonicalInputs: inputs,
          unitSystemId: 'space', exportedAt: '1970-01-01T00:00:00.000Z' });
        const outputs = record.calculation.outputs.map(output => ({ key: output.key, kind: output.kind,
          value: output.kind === 'numeric' ? output.internal.value : output.value,
          specialValue: output.kind === 'numeric' ? output.internal.specialValue : null,
          unit: output.kind === 'numeric' ? output.internal.unit : null }));
        const warnings = record.calculation.applicability.activeWarnings;
        return { ok: true, formula_id: formula.id, outputs, value: outputs[0].value,
          unit: outputs[0].unit, warnings, warning_ids: warnings.map(item => item.id),
          applicability_status: warnings.length ? 'warning_active' : 'not_assessed' };
      } catch (cause) {
        return { ok: false, error: { code: 'CALCULATION_FAILED', message: cause.message } };
      }
    },
  });
};
factories['./plasma-physics.js'] = function(require, module) { module.exports = root.PlasmaPhysics; };
factories['./unit-registry.js'] = function(require, module) { module.exports = root.PlasmaUnitRegistry; };
factories['./examples/wind_pilot/manifest.json'] = function(require, module) {
  module.exports = ${fs.readFileSync(path.join(root, 'examples/wind_pilot/manifest.json'), 'utf8')};
};
`;
  const wrapped = modules.map(file => {
    const code = fs.readFileSync(path.join(root, file), 'utf8');
    return `factories[${JSON.stringify(file)}] = function(require, module, exports) {\nconst global = root;\n${code}\n};`;
  }).join('\n');
  const footer = `
function load(id) {
  if (!factories[id]) throw new Error('Unknown Wind module: ' + id);
  if (!cache[id]) {
    const module = { exports: {} };
    cache[id] = module;
    factories[id](load, module, module.exports);
  }
  return cache[id].exports;
}
root.AlfvenicaResearch = Object.freeze({
  Intake: load('./interval-import.js'),
  Compatibility: load('./model-compatibility.js'),
  Analysis: load('./interval-analysis.js'),
  Sensitivity: load('./research-sensitivity.js'),
  Uncertainty: load('./research-uncertainty.js'),
  Bundle: load('./research-bundle.js'),
  buildIdentity,
  software: { baseApplicationVersion: root.AlfvenicaRelease.baseApplicationVersion,
    baseVersionDoi: root.AlfvenicaRelease.baseVersionDoi },
});
})(globalThis);\n`;
  const code = `/* Generated by build-research-browser.js; do not edit by hand. */\n(function(root) {\n'use strict';\n${bridge}\n${wrapped}\n${footer}`;
  fs.writeFileSync(path.join(root, 'research-browser.js'), code);
  return code;
}
if (require.main === module) console.log(`Built research-browser.js (${Math.round(Buffer.byteLength(build()) / 1024)} KiB)`);
module.exports = Object.freeze({ build });
